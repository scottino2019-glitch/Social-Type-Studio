export function loadAllFonts(): void {
  if (typeof document === 'undefined') return;

  // Load font batches safely
  const BATCH_SIZE = 8;
  const totalBatches = Math.ceil(FONTS_LIST.length / BATCH_SIZE);

  for (let i = 0; i < totalBatches; i++) {
    const linkId = `google-fonts-batch-${i}`;
    if (document.getElementById(linkId)) continue;

    const batch = FONTS_LIST.slice(i * BATCH_SIZE, (i + 1) * BATCH_SIZE);
    const fontQueries = batch
      .map((f) => `family=${f.googleFont.replace(/\s+/g, '+')}`)
      .join('&');

    const link = document.createElement('link');
    link.id = linkId;
    link.rel = 'stylesheet';
    link.href = `https://fonts.googleapis.com/css2?${fontQueries}&display=swap`;
    document.head.appendChild(link);
  }
}

export function loadSingleFont(googleFontQuery: string): void {
  if (typeof document === 'undefined') return;
  const cleanId = `gfont-${googleFontQuery.replace(/[^a-zA-Z0-9]/g, '-')}`;
  if (document.getElementById(cleanId)) return;

  const link = document.createElement('link');
  link.id = cleanId;
  link.rel = 'stylesheet';
  link.href = `https://fonts.googleapis.com/css2?family=${googleFontQuery.replace(/\s+/g, '+')}&display=swap`;
  document.head.appendChild(link);
}
